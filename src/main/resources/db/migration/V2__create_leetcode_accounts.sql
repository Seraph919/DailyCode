CREATE TABLE leetcode_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    discord_user_id BIGINT NOT NULL,
    leetcode_username VARCHAR(100) NOT NULL,
    verified BOOLEAN NOT NULL DEFAULT FALSE,
    verification_token VARCHAR(100),
    verified_at TIMESTAMPTZ,
    last_submission_check_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_leetcode_accounts_discord_user
        FOREIGN KEY (discord_user_id) REFERENCES discord_users (id),
    CONSTRAINT uk_leetcode_accounts_discord_user UNIQUE (discord_user_id),
    CONSTRAINT ck_leetcode_accounts_verification
        CHECK ((verified = FALSE AND verified_at IS NULL)
            OR (verified = TRUE AND verified_at IS NOT NULL))
);

-- Preserve username capitalization while preventing case-only duplicates.
CREATE UNIQUE INDEX uk_leetcode_accounts_username_lower
    ON leetcode_accounts (LOWER(leetcode_username));
