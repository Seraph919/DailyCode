CREATE TABLE problems (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    leetcode_question_id VARCHAR(50) NOT NULL,
    frontend_id VARCHAR(50) NOT NULL,
    title VARCHAR(300) NOT NULL,
    title_slug VARCHAR(300) NOT NULL,
    difficulty VARCHAR(10) NOT NULL,
    paid_only BOOLEAN NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_problems_leetcode_question_id UNIQUE (leetcode_question_id),
    CONSTRAINT uk_problems_title_slug UNIQUE (title_slug),
    CONSTRAINT ck_problems_question_id_not_blank CHECK (leetcode_question_id ~ '[^[:space:]]'),
    CONSTRAINT ck_problems_frontend_id_not_blank CHECK (frontend_id ~ '[^[:space:]]'),
    CONSTRAINT ck_problems_title_not_blank CHECK (title ~ '[^[:space:]]'),
    CONSTRAINT ck_problems_title_slug CHECK (title_slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    CONSTRAINT ck_problems_difficulty CHECK (difficulty IN ('EASY', 'MEDIUM', 'HARD'))
);

CREATE INDEX ix_problems_difficulty_paid_id ON problems (difficulty, paid_only, id);
