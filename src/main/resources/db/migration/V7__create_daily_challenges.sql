CREATE TABLE daily_challenges (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    challenge_id BIGINT NOT NULL,
    problem_id BIGINT NOT NULL,
    assignment_date DATE NOT NULL,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_daily_challenges_challenge FOREIGN KEY (challenge_id) REFERENCES challenges (id),
    CONSTRAINT fk_daily_challenges_problem FOREIGN KEY (problem_id) REFERENCES problems (id),
    CONSTRAINT uk_daily_challenges_day UNIQUE (challenge_id, assignment_date),
    CONSTRAINT uk_daily_challenges_problem UNIQUE (challenge_id, problem_id)
);

CREATE INDEX ix_daily_challenges_problem ON daily_challenges (problem_id);
