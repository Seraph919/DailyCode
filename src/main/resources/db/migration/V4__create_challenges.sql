CREATE TABLE challenges (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    discord_guild_id VARCHAR(20) NOT NULL,
    name VARCHAR(100) NOT NULL,
    created_by_discord_user_id BIGINT NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    timezone VARCHAR(100) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'SCHEDULED',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_challenges_creator
        FOREIGN KEY (created_by_discord_user_id) REFERENCES discord_users (id),
    CONSTRAINT ck_challenges_dates CHECK (end_date >= start_date),
    CONSTRAINT ck_challenges_status CHECK (status IN ('SCHEDULED', 'ACTIVE', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT ck_challenges_guild_not_blank CHECK (btrim(discord_guild_id) <> ''),
    CONSTRAINT ck_challenges_name_not_blank CHECK (btrim(name) <> ''),
    CONSTRAINT ck_challenges_timezone_not_blank CHECK (btrim(timezone) <> '')
);

CREATE INDEX ix_challenges_guild_start_id ON challenges (discord_guild_id, start_date, id);
CREATE INDEX ix_challenges_creator ON challenges (created_by_discord_user_id);
