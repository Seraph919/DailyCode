ALTER TABLE challenge_participants
    ADD CONSTRAINT uk_challenge_participants_id_challenge UNIQUE (id, challenge_id);

ALTER TABLE daily_challenges
    ADD CONSTRAINT uk_daily_challenges_id_challenge UNIQUE (id, challenge_id);

CREATE TABLE daily_progress (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    challenge_id BIGINT NOT NULL,
    participant_id BIGINT NOT NULL,
    daily_challenge_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    submission_id VARCHAR(50),
    completed_at TIMESTAMPTZ,
    verified_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_daily_progress_participant
        FOREIGN KEY (participant_id, challenge_id) REFERENCES challenge_participants (id, challenge_id),
    CONSTRAINT fk_daily_progress_assignment
        FOREIGN KEY (daily_challenge_id, challenge_id) REFERENCES daily_challenges (id, challenge_id),
    CONSTRAINT uk_daily_progress_participant_day UNIQUE (participant_id, daily_challenge_id),
    CONSTRAINT ck_daily_progress_status CHECK (status IN ('PENDING', 'COMPLETED')),
    CONSTRAINT ck_daily_progress_evidence CHECK (
        (status = 'PENDING' AND submission_id IS NULL AND completed_at IS NULL AND verified_at IS NULL)
        OR (status = 'COMPLETED' AND submission_id IS NOT NULL AND submission_id ~ '[^[:space:]]'
            AND completed_at IS NOT NULL AND verified_at IS NOT NULL AND verified_at >= completed_at)
    )
);

CREATE INDEX ix_daily_progress_assignment ON daily_progress (daily_challenge_id);
