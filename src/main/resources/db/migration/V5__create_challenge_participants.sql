CREATE TABLE challenge_participants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    challenge_id BIGINT NOT NULL,
    discord_user_id BIGINT NOT NULL,
    joined_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_challenge_participants_challenge
        FOREIGN KEY (challenge_id) REFERENCES challenges (id),
    CONSTRAINT fk_challenge_participants_user
        FOREIGN KEY (discord_user_id) REFERENCES discord_users (id),
    CONSTRAINT uk_challenge_participants_challenge_user UNIQUE (challenge_id, discord_user_id)
);

CREATE INDEX ix_challenge_participants_user ON challenge_participants (discord_user_id);
CREATE INDEX ix_challenge_participants_challenge_joined_id
    ON challenge_participants (challenge_id, joined_at, id);
